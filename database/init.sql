CREATE DATABASE IF NOT EXISTS auth_db;
CREATE DATABASE IF NOT EXISTS student_db;
CREATE DATABASE IF NOT EXISTS attendance_db;
CREATE DATABASE IF NOT EXISTS marks_db;
CREATE USER IF NOT EXISTS 'auth_user'@'%' IDENTIFIED BY 'auth_pass';
CREATE USER IF NOT EXISTS 'student_user'@'%' IDENTIFIED BY 'student_pass';
CREATE USER IF NOT EXISTS 'attendance_user'@'%' IDENTIFIED BY 'attendance_pass';
CREATE USER IF NOT EXISTS 'marks_user'@'%' IDENTIFIED BY 'marks_pass';
GRANT ALL PRIVILEGES ON auth_db.* TO 'auth_user'@'%';
GRANT ALL PRIVILEGES ON student_db.* TO 'student_user'@'%';
GRANT ALL PRIVILEGES ON attendance_db.* TO 'attendance_user'@'%';
GRANT ALL PRIVILEGES ON marks_db.* TO 'marks_user'@'%';
